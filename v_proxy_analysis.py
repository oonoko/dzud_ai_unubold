#!/usr/bin/env python3
"""
V (бэлчээрийн эмзэг байдал) proxy хувилбаруудын шинжилгээ
"""
import pandas as pd
import numpy as np

df = pd.read_csv('dzud_ai_dataset_advanced.csv')

def minmax(s, mn=None, mx=None):
    mn = s.min() if mn is None else mn
    mx = s.max() if mx is None else mx
    return ((s - mn) / (mx - mn + 1e-8)).clip(0, 1)

# ─────────────────────────────────────────────────────────
# ХУВИЛБАР 1: Энгийн — precip_sum дангаар
# ─────────────────────────────────────────────────────────
df['G1'] = minmax(df['precip_sum'])
df['F1'] = minmax(df['avg_temp'].clip(lower=0))
df['U1'] = minmax(df['precip_sum'] + df['snowfall_sum'] * 0.3)
df['V1'] = 0.45*(1-df['G1']) + 0.35*(1-df['F1']) + 0.20*(1-df['U1'])

# ─────────────────────────────────────────────────────────
# ХУВИЛБАР 2: precip_deficit + snow_cumulative
# ─────────────────────────────────────────────────────────
df['G2'] = 1 - minmax(df['precip_deficit'].clip(lower=0))
df['F2'] = minmax(df['avg_temp'].clip(lower=0))
df['U2'] = minmax(df['snow_cumulative'] + df['precip_sum'])
df['V2'] = 0.45*(1-df['G2']) + 0.35*(1-df['F2']) + 0.20*(1-df['U2'])

# ─────────────────────────────────────────────────────────
# ХУВИЛБАР 3: Улирлын жин — is_winter flag
# ─────────────────────────────────────────────────────────
df['G3'] = minmax(df['precip_sum']) * (1 - 0.3 * df['is_winter'])
df['F3'] = minmax(df['avg_temp'].clip(lower=0)) * (1 - 0.4 * df['is_winter'])
df['U3'] = minmax(df['precip_sum'] + df['snowfall_sum'] * 0.3)
df['V3'] = 0.45*(1-df['G3']) + 0.35*(1-df['F3']) + 0.20*(1-df['U3'])

print('='*65)
print('V (БЭЛЧЭЭРИЙН ЭМЗЭГ БАЙДАЛ) PROXY ШИНЖИЛГЭЭ')
print('='*65)

# ─────────────────────────────────────────────────────────
# 1. Proxy-ийн тайлбар
# ─────────────────────────────────────────────────────────
print('\n1. PROXY ХУВЬСАГЧДЫН ТАЙЛБАР')
print('-'*65)

proxies = [
    ('G* (NDVI орлуулагч)',
     'precip_sum',
     'Хур тунадас их → ургамал сайн → G өндөр',
     df['precip_sum'].min(), df['precip_sum'].max()),

    ('F* (өвсний чанар)',
     'avg_temp (clip≥0)',
     'Зуны дулаан → өвс сайн ургасан → F өндөр',
     0, df['avg_temp'].clip(lower=0).max()),

    ('U* (усны хүртээмж)',
     'precip_sum + snowfall*0.3',
     'Хур тунадас + цасны хайлалт = усны нөөц',
     0, (df['precip_sum'] + df['snowfall_sum']*0.3).max()),
]

for name, col, reason, mn, mx in proxies:
    print(f'\n  {name}')
    print(f'    Багана:  {col}')
    print(f'    Учир:    {reason}')
    print(f'    Хязгаар: {mn:.1f} – {mx:.1f}')

# ─────────────────────────────────────────────────────────
# 2. 3 хувилбарын харьцуулалт
# ─────────────────────────────────────────────────────────
print('\n\n2. 3 PROXY ХУВИЛБАРЫН ХАРЬЦУУЛАЛТ')
print('-'*65)
print(f'{"Хувилбар":<14} {"Корреляц":>10} {"Өвлийн V":>10} {"Зуны V":>10} {"Ялгаа":>10}')
print('-'*55)

results = []
for v, label in [('V1','Хувилбар 1'), ('V2','Хувилбар 2'), ('V3','Хувилбар 3')]:
    corr = df[v].corr(df['target_dzud'])
    w = df[df['month'].isin([11,12,1,2,3])][v].mean()
    s = df[df['month'].isin([6,7,8])][v].mean()
    diff = w - s
    results.append((label, corr, w, s, diff))
    print(f'{label:<14} {corr:>+10.4f} {w:>10.3f} {s:>10.3f} {diff:>+10.3f}')

print('\n  Тайлбар:')
print('  • Корреляц: target_dzud-тай хамаарал (өндөр = сайн)')
print('  • Өвлийн V: өвлийн сарт V өндөр байх ёстой (бэлчээр муу)')
print('  • Зуны V:   зуны сарт V бага байх ёстой (бэлчээр сайн)')
print('  • Ялгаа:    өвөл-зун ялгаа их байх нь физик утгатай')

# ─────────────────────────────────────────────────────────
# 3. Сар бүрийн V утга
# ─────────────────────────────────────────────────────────
print('\n\n3. САР БҮРИЙН V УТГА (Хувилбар 1)')
print('-'*65)
print(f'{"Сар":<6} {"V1":>8} {"G1":>8} {"F1":>8} {"U1":>8} {"Тайлбар"}')
print('-'*55)

month_names = {1:'1-р (Зуд)', 2:'2-р (Зуд)', 3:'3-р (Зуд)',
               4:'4-р', 5:'5-р', 6:'6-р (Зун)',
               7:'7-р (Зун)', 8:'8-р (Зун)', 9:'9-р',
               10:'10-р', 11:'11-р (Зуд)', 12:'12-р (Зуд)'}

for m in range(1, 13):
    sub = df[df['month'] == m]
    v = sub['V1'].mean()
    g = sub['G1'].mean()
    f = sub['F1'].mean()
    u = sub['U1'].mean()
    note = month_names.get(m, '')
    bar = '█' * int(v * 20)
    print(f'{note:<12} {v:>6.3f}  {g:>6.3f}  {f:>6.3f}  {u:>6.3f}  {bar}')

# ─────────────────────────────────────────────────────────
# 4. Хамгийн тохиромжтой proxy
# ─────────────────────────────────────────────────────────
print('\n\n4. ХАМГИЙН ТОХИРОМЖТОЙ PROXY — ХУВИЛБАР 1')
print('-'*65)
print("""
  V = 0.45*(1 - G*) + 0.35*(1 - F*) + 0.20*(1 - U*)

  G* = normalize(precip_sum, 0, 30)
       → precip_sum их = бэлчээр чийглэг = G өндөр = (1-G) бага
       → precip_sum бага = хуурай = G бага = (1-G) өндөр = V өндөр ✅

  F* = normalize(max(avg_temp, 0), 0, 27)
       → Зуны температур өндөр = өвс сайн = F өндөр = (1-F) бага
       → Өвлийн температур хасах = өвс байхгүй = F≈0 = (1-F)≈1 = V өндөр ✅

  U* = normalize(precip_sum + 0.3*snowfall_sum, 0, 40)
       → Хур тунадас + цасны хайлалт = усны нөөц = U өндөр = (1-U) бага
       → Хуурай = U бага = (1-U) өндөр = V өндөр ✅
""")

# ─────────────────────────────────────────────────────────
# 5. Дипломын тайланд бичих хэлбэр
# ─────────────────────────────────────────────────────────
print('\n5. ДИПЛОМЫН ТАЙЛАНД БИЧИХ ХЭЛБЭР')
print('-'*65)
print("""
  Бэлчээрийн эмзэг байдлын V бүрэлдэхүүнийг тооцоолоход
  NDVI болон бэлчээрийн даацын бодит өгөгдөл байхгүй тул
  цаг уурын өгөгдлөөс гаргасан proxy хувьсагчдаар орлуулав:

  ┌─────────────────────────────────────────────────────┐
  │  Жинхэнэ хувьсагч  │  Proxy                        │
  ├─────────────────────────────────────────────────────┤
  │  G (NDVI)           │  normalize(precip_sum, 0, 30) │
  │  F (өвсний чанар)   │  normalize(avg_temp⁺, 0, 27)  │
  │  U (усны хүртээмж)  │  normalize(P + 0.3S, 0, 40)   │
  └─────────────────────────────────────────────────────┘

  Энэхүү орлуулалтын үндэслэл:
  • Хур тунадас (precip_sum) нь ургамлын ургалтын гол хүчин
    зүйл тул NDVI-ийн proxy болж чадна (Nicholson et al., 1990)
  • Зуны температур нь өвсний ургалтын чанарыг тодорхойлно
  • Нийт чийг (хур тунадас + цасны хайлалт) нь усны нөөцийн
    ойролцоо үзүүлэлт болно

  Ирээдүйн хөгжүүлэлтэд MODIS NDVI (250м нарийвчлал) болон
  МХЕГ-ийн бэлчээрийн зураглалын өгөгдлийг нэгтгэхээр
  төлөвлөсөн.
""")

print('='*65)
print('Шинжилгээ дууслаа.')
print('='*65)
